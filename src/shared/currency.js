export function formatCurrency(amount, code = "USD") {
  const symbol = currencies.find((item) => item.code === code)?.symbol || code;
  const value = Number(amount);
  return `${symbol} ${new Intl.NumberFormat("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(Number.isFinite(value) ? value : 0)}`;
}
